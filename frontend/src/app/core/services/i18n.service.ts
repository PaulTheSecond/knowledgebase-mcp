  private getInitialLocale(): Locale {
    const saved = localStorage.getItem('kmcp_locale');
    if (saved === 'en' || saved === 'ru') return saved;
    return 'ru';
  }

  setLocale(locale: Locale): void {
    this.localeSignal.set(locale);
    localStorage.setItem('kmcp_locale', locale);
    document.documentElement.lang = locale;
  }

  t(key: string, params: Record<string, string | number> = {}): string {
    const loc = this.localeSignal();
    let text = this.translations[loc][key] || this.translations['ru'][key] || key;
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
    return text;
  }
